#!/usr/bin/env bash
# FILE: tools/hooks/answer_judge.sh — судья упаковки смысла (К-42, ADR-123 §2)
#
# Зачем. К-39 машине поддаётся целиком, К-42 — нет: «расколотый орех» есть суждение, а не
# формат. Детерминированные признаки в answer_check.sh ловят четыре грубых класса; остальное
# видит только модель. Судья отдаёт ответ роли на разбор отдельной модели по рубрике К-42.
#
# Режим ПРЕДУПРЕДИТЕЛЬНЫЙ: ответ не блокируется никогда, вердикт уходит в замер
# (.claude/answer_check.log, агрегирует tools/answer_stats.sh). Мотив — судья недетерминирован:
# ложный блок дороже пропущенного дефекта, а замер за десять сессий стоит дороже вердикта за один.
#
# ВКЛЮЧЕНИЕ. Судья молчит, пока нет файла-выключателя `.claude/answer_judge.on`. Причина —
# headless-вызов `claude -p` требует отдельной авторизации CLI; на машине Owner 2026-08-10 он
# отвечает «Not logged in · Please run /login». Порядок включения:
#   1) в терминале: claude  → /login
#   2) touch .claude/answer_judge.on
# Проверить включение: bash tools/hooks/answer_judge.sh --selfcheck
#
# Рекурсия закрыта переменной ANSWER_JUDGE_INNER: внутренний вызов работает в том же каталоге,
# видит тот же .claude/settings.json и без неё вызвал бы судью на своём же ответе.
set -u

DIR="$(cd "$(dirname "$0")" && pwd)"
LOG=".claude/answer_check.log"
MODEL="${ANSWER_JUDGE_MODEL:-claude-haiku-4-5-20251001}"

log() { [ -d .claude ] && printf '%s\n' "$1" >> "$LOG" 2>/dev/null; return 0; }
stamp() { date -u '+%Y-%m-%dT%H:%M:%SZ'; }

[ "${ANSWER_JUDGE_INNER:-0}" = "1" ] && exit 0        # рекурсия
[ -f .claude/answer_judge.on ] || [ "${1:-}" = "--selfcheck" ] || exit 0

command -v claude >/dev/null 2>&1 || {
  printf 'answer_judge: CLI claude не найден, судья пропущен\n' >&2
  log "$(stamp)	СУДЬЯ-ОТКАЗ	CLI не найден"; exit 0; }
command -v python3 >/dev/null 2>&1 || exit 0

RUBRIC='Ты проверяешь ЧУЖОЙ ответ по правилу К-42 «упаковка смысла» проекта dom-prorab-ecom-arch.
Правило: ответ обязан отдавать готовый смысловой результат, а не сырьё, из которого читатель
соберёт результат сам. Проверь шесть вещей:
1. вывод стоит РАНЬШЕ доказательства, а не после цепочки фактов;
2. причинно-следственную связь сформулировал автор, а не оставил читателю сопоставлять два места;
3. это результат, а не журнал собственных действий;
4. числа выведены только те, что меняют вывод или нужны для решения;
5. каждый абзац несёт одну смысловую операцию;
6. термины и коды работают на понимание, а не на демонстрацию точности.
Ответь РОВНО одной строкой без пояснений.
Если нарушений нет: OK
Если есть: НЕ ОК: <дословная строка-нарушитель из ответа> — <номер пункта и в чём дело>
Разбираемый ответ ниже, между маркерами.'

if [ "${1:-}" = "--selfcheck" ]; then
  TXT=$(mktemp); printf '%s\n' 'Сделано: ничего.' 'Нужно от Owner: ничего.' 'Рекомендация: ничего.' > "$TXT"
else
  EXTRACT="$DIR/answer_extract.py"
  [ -f "$EXTRACT" ] || exit 0
  TXT=$(mktemp)
  python3 "$EXTRACT" "$TXT"; rc=$?
  [ "$rc" -eq 0 ] || { rm -f "$TXT"; exit 0; }        # повторный заход либо нечего разбирать
  [ -s "$TXT" ] || { rm -f "$TXT"; exit 0; }
fi

VERDICT=$(
  { printf '%s\n\n===ОТВЕТ===\n' "$RUBRIC"; cat "$TXT"; printf '\n===КОНЕЦ===\n'; } \
  | ANSWER_JUDGE_INNER=1 claude -p --model "$MODEL" 2>&1 | tr '\n' ' ' | sed 's/[[:space:]]*$//'
)
rm -f "$TXT"

case "$VERDICT" in
  ""|*"Not logged in"*|*"Please run /login"*)
    printf 'answer_judge: CLI claude не авторизован — судья не работает. Порядок включения в шапке %s\n' "$DIR/answer_judge.sh" >&2
    log "$(stamp)	СУДЬЯ-ОТКАЗ	CLI не авторизован"
    exit 0 ;;
  OK*|ОК*)
    log "$(stamp)	СУДЬЯ	OK"
    [ "${1:-}" = "--selfcheck" ] && echo "answer_judge: судья отвечает, вердикт «$VERDICT»"
    exit 0 ;;
esac

# Вердикт печатается строкой-нарушителем, а не меткой: метка непроверяема (К-28).
printf 'СУДЬЯ УПАКОВКИ (К-42, предупреждение, ответ не блокируется):\n  %s\n' "$VERDICT" >&2
log "$(stamp)	СУДЬЯ-ЗАМЕЧАНИЕ	$VERDICT"
exit 0
