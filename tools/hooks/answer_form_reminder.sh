#!/usr/bin/env bash
# FILE: tools/hooks/answer_form_reminder.sh — напоминание формы ответа (К-39, К-42; ADR-122 §5)
# Хук UserPromptSubmit Claude Code: печатаемое уходит в контекст роли перед её работой.
# Смысл — тонус: правило лежит в конвенциях, но между стартом сессии и ответом проходят
# десятки шагов, и к моменту ответа оно уже вне окна внимания. Проверка формы — отдельный
# носитель (tools/hooks/answer_check.sh); это напоминание её не заменяет.
set -u
cat <<'EOF'
[Форма ответа к Owner — К-39 и К-42, проверяется машинно хуком Stop перед выдачей]
Шапка ровно три строки: «Сделано:» · «Нужно от Owner:» · «Рекомендация:», каждая одной строкой, нечего написать — «нет».
После шапки не более 25 непустых строк. Абзац не длиннее трёх строк; перечень абзацем не считается.
Вывод раньше доказательства: сначала что получилось и что это значит, фактура — после вывода как подтверждение.
Причинно-следственную связь формулируешь ты, а не читатель: сопоставление двух мест пишется фразой, а не выкладывается материалом.
Журнал собственных действий, необъяснённые числа и телеметрия в текст к Owner не идут.
Машинная часть (session-блок, патчи, брифы, содержимое файлов) в чат не печатается: её носители — файлы репо и описание коммита.
EOF
