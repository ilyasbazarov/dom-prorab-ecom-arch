#!/usr/bin/env bash
# FILE: tools/hooks/answer_check.sh — машинная проверка формы ответа роли (К-39, ADR-122)
#
# Зачем. Текст к Owner — единственный артефакт проекта, который не лежит в репо и потому
# не виден ни pre-commit хуку, ни tools/verify.sh. Правило формы без носителя проверки
# держится на памяти роли и не держится. Этот скрипт даёт форме носитель: хук Stop
# Claude Code читает готовый ответ и возвращает его роли на переписывание.
#
# Режимы запуска:
#   (без аргументов)  — хук Stop: JSON на stdin, текст берётся из transcript_path
#   --text <файл>     — проверка готового текста из файла (самотест, К-34)
#
# Два слоя строгости (ADR-125 §1, §2). БЛОКИРУЮЩИЙ слой возвращает ответ роли: пять признаков
# формы (К-39) плюс УПАКОВКА-1 и УПАКОВКА-2. ПРЕДУПРЕДИТЕЛЬНЫЙ слой пишет вердикт в замер и
# ответ не возвращает: УПАКОВКА-3 и УПАКОВКА-4. Причина разведения — эти два признака бьют по
# содержанию, которое ТРЕБУЮТ принятые правила: перечень адресов отчёта К-36 несёт пять и более
# чисел при `/`, а строка приёмки К-28 и вердикт по нескольким записям несут коды пачкой. Три
# законных ответа были возвращены в поле за сутки; проверка наказывала исполнение accepted-правил.
#
# Коды выхода: 0 — форма сошлась, либо сработал только предупредительный слой, либо это
# повторный заход, либо внутренний отказ проверки; 2 — нарушение блокирующего слоя, stderr
# уходит модели и она переписывает ответ.
#
# Отказ проверки не тихий (CLAUDE.md §Старт п.4): любой внутренний сбой печатается в
# stderr и дописывается в .claude/answer_check.log, но работу не блокирует.
set -u

note() {
  printf 'answer_check: %s\n' "$*" >&2
  [ -d .claude ] && printf '%s\n' "answer_check: $*" >> .claude/answer_check.log 2>/dev/null
  return 0
}

# Локаль задаётся явно (К-35): под байтовой семантикой классы символов в разборе
# занижаются молча, а вердикт при этом печатается тот же.
for cand in ru_RU.UTF-8 en_US.UTF-8 C.UTF-8; do
  if locale -a 2>/dev/null | grep -qix -e "$cand" -e "${cand/UTF-8/utf8}"; then
    export LC_ALL="$cand"; break
  fi
done

TMPS=""
trap '[ -n "$TMPS" ] && rm -f $TMPS' EXIT

MODE=hook                   # --text: самотест и разовая проверка, в замер не идёт
REPEAT=0                    # второй проход по одному ответу: предупредительный, см. ADR-125 §3
if [ "${1:-}" = "--text" ]; then
  MODE=text
  TXT="${2:-}"
  [ -f "$TXT" ] || { note "не найден файл текста '${2:-}'"; exit 0; }
else
  command -v python3 >/dev/null 2>&1 || { note "нет python3, форма ответа НЕ проверена"; exit 0; }
  EXTRACT="$(cd "$(dirname "$0")" && pwd)/answer_extract.py"
  [ -f "$EXTRACT" ] || { note "не найден $EXTRACT, форма ответа НЕ проверена"; exit 0; }
  TXT=$(mktemp); TMPS="$TXT"
  python3 "$EXTRACT" "$TXT"; rc=$?
  case "$rc" in
    0) ;;
    4) REPEAT=1 ;;                                   # повторный заход: меряем, но не блокируем
    *) note "транскрипт не разобран, форма ответа НЕ проверена"; exit 0 ;;
  esac
  [ -s "$TXT" ] || exit 0                            # текста нет — проверять нечего
fi

# ── разбор текста ───────────────────────────────────────────────────────────────
NUM=0                       # порядковый номер непустой строки
H1=""; H2=""; H3=""
AFTER=0                     # непустых строк после шапки (лимит К-39 §2)
PARA=0; MAXPARA=0; MAXPARA_AT=""
FENCE=0
MACHINE=""                  # первая напечатанная в чат строка машинной части
FORKS=0                     # блоков развилки (К-25); каждый расширяет лимит
LASTLINE=""                 # последняя непустая строка — ловит вывод, спрятанный в конец
JOURNAL=0                   # строк-шагов журнала действий
TELEM=""; CODES=""          # первые строки-нарушители по числам и по плотности кодов

while IFS= read -r raw || [ -n "$raw" ]; do
  line=$(printf '%s' "$raw" | sed 's/[[:space:]]*$//')
  trimmed=$(printf '%s' "$line" | sed 's/^[[:space:]]*//')

  case "$trimmed" in '```'*) FENCE=$((1-FENCE)); PARA=0; continue;; esac
  [ -n "$trimmed" ] || { PARA=0; continue; }

  NUM=$((NUM+1))
  norm=$(printf '%s' "$trimmed" | tr -d '*#' | sed 's/^[[:space:]]*//')

  case "$NUM" in
    1) H1="$norm" ;;
    2) H2="$norm" ;;
    3) H3="$norm" ;;
    *) AFTER=$((AFTER+1)) ;;
  esac

  # Носители машинной части, напечатанные в чат (К-39 §7)
  if [ -z "$MACHINE" ]; then
    case "$trimmed" in
      '=== SESSION LOG'*|'=== END SESSION'*|'## SESSION_LOG'*|'## STATE_PATCH'*|\
      '## NEW_DECISIONS'*|'## REGISTER_PATCHES'*|'## FILE_PATCHES'*|\
      '## NEW_CONVENTIONS'*|'## JOURNAL_ROW'*) MACHINE="$trimmed" ;;
    esac
  fi

  # ── признаки упаковки смысла (К-42), собираются на том же проходе ──
  LASTLINE="$trimmed"
  case "$norm" in "Развилка Р-"*) FORKS=$((FORKS+1)) ;; esac
  case "$norm" in
    'Сначала '*|'Затем '*|'Потом '*|'Далее '*|'После этого '*|'После чего '*) JOURNAL=$((JOURNAL+1)) ;;
  esac
  if [ -z "$TELEM" ] && [ "$FENCE" = "0" ]; then
    case "$trimmed" in
      *'/'*)
        n=$(printf '%s' "$trimmed" | grep -o '[0-9][0-9]*' | wc -l | tr -d ' ')
        [ "$n" -ge 5 ] && TELEM="$trimmed" ;;
    esac
  fi
  if [ -z "$CODES" ] && [ "$FENCE" = "0" ]; then
    c=$(printf '%s' "$trimmed" | grep -oE '(ADR|OQ|BQ|CQ|P)-[0-9]+|К-[0-9]+' | wc -l | tr -d ' ')
    [ "$c" -ge 4 ] && CODES="$trimmed"
  fi

  # Длина абзаца. Список, таблица, заголовок, цитата, строка внутри блока кода и
  # продолжение с отступом абзацем не являются: К-39 §3 бьёт по слитному тексту.
  [ "$FENCE" = "0" ] || { PARA=0; continue; }
  case "$trimmed" in
    -*|'*'*|'|'*|'#'*|'>'*|'§'*|[0-9].*|[0-9][0-9].*|[0-9]')'*) PARA=0; continue;;
  esac
  case "$line" in '  '*|'	'*) continue;; esac
  PARA=$((PARA+1))
  if [ "$PARA" -gt "$MAXPARA" ]; then MAXPARA="$PARA"; MAXPARA_AT="$trimmed"; fi
done < "$TXT"

# ── вердикты (К-28: печатаются сами нарушения, а не метка PASS/FAIL) ────────────
# Каждое нарушение несёт код: ФОРМА-n — К-39, машинно однозначна; УПАКОВКА-n — К-42,
# признак косвенный. Коды копятся в .claude/answer_check.log и агрегируются
# tools/answer_stats.sh: правило чинится по замеру, а не по памяти (ADR-123 §4).
V=0
OUT=""
KEYS=""
W=0
WOUT=""
WKEYS=""

# Предупредительный слой (ADR-125 §2): вердикт идёт в замер и в stderr, ответ не возвращается.
warn() { W=$((W+1)); WKEYS="$WKEYS,$1"; WOUT="$WOUT
  $W. [$1] $2"; }

# Блокирующий слой. Счёт ведётся и на втором проходе — иначе замер не отличит «переписали
# чисто» от «переписали и снова мимо». Не блокирует второй проход только выдача (ADR-125 §3):
# пара «хук ↔ модель» ушла бы в цикл, а вердикт при этом сохраняется строкой ПОВТОР-ВОЗВРАТ.
viol() { V=$((V+1)); KEYS="$KEYS,$1"; OUT="$OUT
  $V. [$1] $2"; }

case "$H1" in "Сделано:"*) ;; *) viol ФОРМА-1 "строка 1 шапки не «Сделано:», а «${H1:-<пусто>}»";; esac
case "$H2" in "Нужно от Owner:"*) ;; *) viol ФОРМА-1 "строка 2 шапки не «Нужно от Owner:», а «${H2:-<пусто>}»";; esac
case "$H3" in
  "Рекомендация:"*)
    rec=$(printf '%s' "$H3" | sed 's/^Рекомендация:[[:space:]]*//')
    if [ -z "$rec" ]; then
      viol ФОРМА-2 "строка «Рекомендация:» пуста"
    else
      # Альтернация целыми словами, а не класс [Сс]: bracket-выражение с кириллицей
      # распадается на байты под байтовой семантикой и молча не срабатывает (К-35).
      case "$rec" in
        'см. ниже'*|'См. ниже'*|'ниже'*|'Ниже'*|'в тексте'*|'В тексте'*|'—'|'-')
          viol ФОРМА-2 "строка «Рекомендация:» отсылает вниз вместо содержания: «${rec}» (К-39 §6, К-25)";;
      esac
    fi ;;
  *) viol ФОРМА-1 "строка 3 шапки не «Рекомендация:», а «${H3:-<пусто>}»";;
esac

# Лимит расширяется блоками развилки: решение Owner требует вариантов и последствий,
# и сжимать его до тезиса — потеря существенного (К-25, ADR-123 §3). Развилок больше
# двух в одном ответе не подаётся: это сигнал, что сессию надо делить.
LIMIT=25
if [ "$FORKS" -gt 0 ]; then
  n=$FORKS; [ "$n" -gt 2 ] && n=2
  LIMIT=$((25 + 12 * n))
fi
[ "$FORKS" -le 2 ] || viol ФОРМА-3 "развилок в одном ответе $FORKS при пределе 2 (К-25): лишние переносятся в следующую сессию"
[ "$AFTER" -le "$LIMIT" ] || viol ФОРМА-3 "текст к Owner после шапки — $AFTER непустых строк при лимите $LIMIT (К-39 §2, развилок $FORKS): лишнее уходит в файл репо или в следующую сессию"
[ "$MAXPARA" -le 3 ] || viol ФОРМА-4 "абзац длиной $MAXPARA строк при лимите 3 (К-39 §3), начало: «${MAXPARA_AT}»"
[ -z "$MACHINE" ] || viol ФОРМА-5 "машинная часть напечатана в чат, строка «${MACHINE}» (К-39 §7): её носители — файлы репо и описание коммита"

# ── упаковка смысла (К-42): признаки косвенные, но проверяемые строкой ──────────
case "$LASTLINE" in
  'Поэтому'*|'Таким образом'*|'Итого'*|'Следовательно'*|'Отсюда'*|'Значит,'*|'В итоге'*|'Вывод:'*)
    viol УПАКОВКА-1 "вывод спрятан в последнюю строку: «${LASTLINE}» (К-42 §1, §7) — он должен стоять до доказательства";;
esac
[ "$JOURNAL" -lt 3 ] || viol УПАКОВКА-2 "журнал собственных действий вместо результата: строк-шагов «сначала/затем/потом/далее» — $JOURNAL (К-42 §3)"

# УПАКОВКА-3 и УПАКОВКА-4 — ПРЕДУПРЕЖДЕНИЯ, а не возвраты (ADR-125 §1). Оба признака
# неотличимы от содержания, которое требуют принятые правила: перечень адресов отчёта К-36
# всегда даёт пять и более чисел при `/`, строка приёмки по К-28 — тоже, а вердикт по
# нескольким записям журнала кладёт коды пачкой и работает по К-42 §6. Блокировать их
# значит машинно наказывать исполнение accepted-правил; замер сохраняется полностью.
[ -z "$TELEM" ] || warn УПАКОВКА-3 "числа плотно, строка «${TELEM}» (К-42 §4): проверь, каждое ли меняет вывод — отчёт К-36 и строка приёмки К-28 законны и возврата не требуют"
[ -z "$CODES" ] || warn УПАКОВКА-4 "плотность кодов в одной строке (К-42 §6), строка «${CODES}»: код остаётся, если читатель что-то понимает благодаря ему"

# Замер (К-22, К-29 — время в UTC с суффиксом Z): одна строка на ответ. Пишется только в
# режиме хука: прогоны --text это самотест, и в замере реальных ответов им не место.
# Метка ПОВТОР помечает второй проход по одному ответу: по паре строк ОТВЕТ→ПОВТОР видно,
# исправлен ли возвращённый ответ, — без этого замер считал возвраты, но не их исход.
if [ "$MODE" = "hook" ] && [ -d .claude ]; then
  TS=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
  TAG=""; [ "$REPEAT" = "1" ] && TAG="ПОВТОР-"
  {
    if [ "$V" -gt 0 ]; then
      printf '%s\t%sВОЗВРАТ\t%d\t%s\n' "$TS" "$TAG" "$V" "${KEYS#,}"
    elif [ "$W" -gt 0 ]; then
      printf '%s\t%sПРЕДУПРЕЖДЕНИЕ\t%d\t%s\n' "$TS" "$TAG" "$W" "${WKEYS#,}"
    else
      printf '%s\t%sOK\t0\n' "$TS" "$TAG"
    fi
  } >> .claude/answer_check.log 2>/dev/null
fi

# Предупреждения печатаются всегда, но ответ ими не возвращается (ADR-125 §2).
[ "$W" -eq 0 ] || printf 'ПРЕДУПРЕЖДЕНИЕ УПАКОВКИ — ответ НЕ возвращён, вердикт ушёл в замер:%s\n' "$WOUT" >&2

[ "$V" -eq 0 ] && exit 0

# Второй проход: нарушение названо и посчитано, но выдача не блокируется (ADR-125 §3).
if [ "$REPEAT" = "1" ]; then
  printf 'ПОВТОРНЫЙ ЗАХОД — ответ НЕ возвращён второй раз, нарушений %d ушло в замер:%s\n' "$V" "$OUT" >&2
  exit 0
fi

{
  printf 'ОТВЕТ ВОЗВРАЩЁН — нарушений %d (tools/hooks/answer_check.sh):%s\n' "$V" "$OUT"
  printf '\nПерепиши по К-39 и К-42: шапка из трёх строк, вывод раньше доказательства, не более\n'
  printf '25 строк после шапки (плюс 12 на каждую развилку), абзац не длиннее трёх строк,\n'
  printf 'машинная часть в чат не печатается. Сокращать существенное молча запрещено —\n'
  printf 'выброшенное назови строкой.\n'
} >&2
exit 2
